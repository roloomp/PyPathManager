import sys
from PyQt6.QtCore import PYQT_VERSION_STR, QT_VERSION_STR
from PyQt6.QtWidgets import QDialog, QMessageBox, QTextBrowser, QVBoxLayout

DOCS = """
<h2>PATH</h2>
<p>В таблице показаны интерпретаторы Python, найденные в реестре Windows. Активный выделен цветом.</p>
<ul>
<li><b>Перечитать</b> - заново найти интерпретаторы.</li>
<li><b>Сделать активным</b> - ставит каталоги выбранного Python и его Scripts первыми в PATH пользователя.
Если Python есть в системном PATH, оттуда эти каталоги тоже убираются; для этого нужны права администратора.
После изменения перезапустите терминал.</li>
</ul>

<h2>Библиотеки</h2>
<p>Список библиотек выбранного интерпретатора или venv. Жёлтая ячейка в столбце «Последняя версия» значит, что есть обновление.
Библиотеки отмечаются галочками. Клик по заголовку столбца сортирует таблицу. Поле справа от заголовка ищет по имени;
все операции работают только с найденными (видимыми) строками.</p>
<ul>
<li><b>Установить</b> - имена через пробел. Версию можно указать, если пакет один.</li>
<li><b>Обновить</b> - обновляет отмеченные библиотеки.</li>
<li><b>Версия</b> - для одной отмеченной библиотеки выбрать любую доступную версию (новее или старее).</li>
<li><b>Выбрать всё</b> - отметить или снять все видимые.</li>
<li><b>Удалить</b> - перед удалением показывает, какие пакеты требуют удаляемые.
pip, setuptools и wheel удалить нельзя.</li>
<li><b>Экспорт библиотек</b> - записать отмеченные в requirements.txt.</li>
<li><b>Импорт библиотек</b> - установить из requirements.txt.</li>
</ul>

<h2>venv</h2>
<ul>
<li><b>Создать</b> - новое окружение: Python берётся из списка справа, затем выбираются папка проекта и название.</li>
<li><b>Добавить</b> - добавить в список уже существующее окружение.</li>
<li><b>Удалить</b> - удалить окружение с диска или только убрать из списка.</li>
<li><b>Изменить</b> - пересоздать окружение на Python, выбранном в списке; библиотеки переустанавливаются.</li>
<li><b>Выбрать</b> - показать библиотеки окружения; выбор запоминается между запусками.</li>
<li><b>Запустить</b> - выполнить выбранный файл Python в окружении, в новой консоли.</li>
</ul>
"""


def show_docs(parent):
    dlg = QDialog(parent)
    dlg.setWindowTitle("Документация")
    dlg.resize(640, 560)
    view = QTextBrowser()
    view.setHtml(DOCS)
    layout = QVBoxLayout(dlg)
    layout.addWidget(view)
    dlg.exec()


def show_about(parent):
    QMessageBox.about(
        parent, "О приложении",
        "<h3>PyPath Manager</h3>"
        "<p>Утилита для управления Python-окружением в Windows: интерпретаторы и PATH, "
        "виртуальные окружения, библиотеки.</p>"
        f"<p>Python {sys.version.split()[0]}, PyQt {PYQT_VERSION_STR}, Qt {QT_VERSION_STR}</p>")
