def show_docs(parent):
    """Показывает окно с документацией."""
    dlg = QDialog(parent)
    dlg.setWindowTitle("Документация")
    dlg.resize(640, 560)
    view = QTextBrowser()
    view.setHtml(DOCS)
    layout = QVBoxLayout(dlg)
    layout.addWidget(view)
    dlg.exec()


